/** The three classes, phrased for everyday users. */
export type VerdictType = "real" | "tampered" | "ai";

export const verdicts: VerdictType[] = ["real", "tampered", "ai"];

/** Full verdict, e.g. on the results screen. */
export const verdictLabel: Record<VerdictType, string> = {
  real: "Likely Real",
  tampered: "Likely Edited",
  ai: "Likely AI",
};

/** One-word form for badges and filters. */
export const verdictShortLabel: Record<VerdictType, string> = {
  real: "Real",
  tampered: "Edited",
  ai: "AI",
};

/** What this verdict means, in one sentence. */
export const verdictExplanation: Record<VerdictType, string> = {
  real: "Nothing in the photo points to editing or generation.",
  tampered: "A real photo where part of the image was changed, added or removed.",
  ai: "The whole image looks generated rather than photographed.",
};

/** Whether the classifier flagged something worth pointing at on the photo. */
export const hasAnomaly = (verdict: VerdictType) => verdict !== "real";

export type VerdictFilter = "all" | VerdictType;

export const verdictFilters: VerdictFilter[] = ["all", "real", "tampered", "ai"];

export const verdictFilterTitle = (filter: VerdictFilter) =>
  filter === "all" ? "All" : verdictShortLabel[filter];

/**
 * Plain-language copy for freshly analyzed images. It describes what the
 * detector concluded and what the user can check themselves; it never claims
 * specific visual evidence the model didn't report.
 */
export interface VerdictCopy {
  summary: string;
  action: string;
  /** Things the user can look for to confirm or challenge the verdict. */
  findings: string[];
}


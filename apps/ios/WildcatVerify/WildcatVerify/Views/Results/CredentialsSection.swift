import SwiftUI

/// Content Credentials found in the photo's file: who made it and how, as the
/// file itself claims.
struct CredentialsSection: View {
    let credentials: ContentCredentials

    private var sourceText: String? {
        switch credentials.source {
        case .aiGenerated: "Says it was generated by AI"
        case .aiEdited: "Says it includes AI-generated parts"
        case .camera: "Says it was taken with a camera"
        case .unspecified: nil
        }
    }

    private var sourceColor: Color {
        switch credentials.source {
        case .aiGenerated: VerdictType.ai.textColor
        case .aiEdited: VerdictType.tampered.textColor
        case .camera: VerdictType.real.textColor
        case .unspecified: .secondary
        }
    }

    var body: some View {
        Section {
            if let sourceText {
                Label {
                    Text(sourceText).bold()
                } icon: {
                    Image(systemName: "tag.fill")
                        .foregroundStyle(sourceColor)
                }
            }
            if let generator = credentials.generator {
                LabeledContent("Made with", value: generator)
            }
            if !credentials.actions.isEmpty {
                LabeledContent("History", value: credentials.actions.joined(separator: ", "))
            }
        } header: {
            Text("Content Credentials")
        } footer: {
            Text("Read from the photo's file. Look Again doesn't verify the signature yet, so treat this as a strong clue, not proof.")
        }
        .accessibilityElement(children: .contain)
    }
}

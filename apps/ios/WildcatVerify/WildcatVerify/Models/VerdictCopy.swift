/// Plain-language copy for freshly analyzed images. It describes what the
/// detector concluded and what the user can check themselves; it never claims
/// specific visual evidence the model didn't report.
struct VerdictCopy {
    var summary: String
    var action: String
    /// Things the user can look for to confirm or challenge the verdict.
    var findings: [String]

    static func `for`(_ verdict: VerdictType) -> VerdictCopy {
        switch verdict {
        case .real:
            VerdictCopy(
                summary: "The detector didn't find strong signs that this image was generated by AI. That isn't proof it's genuine: it can still be edited or shared with a misleading caption.",
                action: "Check who posted it first and whether the caption fits before sharing.",
                findings: [
                    "Shadows and lighting agree across the whole scene",
                    "The same event appears in other people's photos",
                    "The caption's date and place match what's shown",
                ]
            )
        case .tampered:
            VerdictCopy(
                summary: "Part of this photo looks inconsistent with the rest, as if something was added, removed or retouched.",
                action: "Look for the original photo before sharing it.",
                findings: [
                    "One area sharper or softer than its surroundings",
                    "Edges that look cut out or smudged",
                    "Text that stays flat where the surface bends",
                ]
            )
        case .ai:
            VerdictCopy(
                summary: "The detector found patterns it associates with AI-generated images.",
                action: "Don't share it as a real photo without confirming where it came from.",
                findings: [
                    "Hands, teeth and text: extra fingers or letters that don't spell anything",
                    "Pairs that don't match, like earrings or glasses",
                    "Hair or edges that melt into the background",
                ]
            )
        }
    }
}

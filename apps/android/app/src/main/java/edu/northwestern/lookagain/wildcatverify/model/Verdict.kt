package edu.northwestern.lookagain.wildcatverify.model

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/** The three classes, phrased for everyday users. Colors and icons live in `ui/theme/VerdictStyle.kt`. */
@Serializable
enum class VerdictType {
    @SerialName("real") REAL,
    @SerialName("tampered") TAMPERED,
    @SerialName("ai") AI;

    /** Full verdict, e.g. on the results screen. */
    val label: String
        get() = when (this) {
            REAL -> "Likely Real"
            TAMPERED -> "Likely Edited"
            AI -> "Likely AI"
        }

    /** One-word form for badges and filters. */
    val shortLabel: String
        get() = when (this) {
            REAL -> "Real"
            TAMPERED -> "Edited"
            AI -> "AI"
        }

    /** What this verdict means, in one sentence. */
    val explanation: String
        get() = when (this) {
            REAL -> "Nothing in the photo points to editing or generation."
            TAMPERED -> "A real photo where part of the image was changed, added or removed."
            AI -> "The whole image looks generated rather than photographed."
        }

    /** Whether the classifier flagged something worth pointing at on the photo. */
    val hasAnomaly: Boolean get() = this != REAL
}

/** Search scope for My Checks. */
enum class VerdictFilter {
    ALL, REAL, TAMPERED, AI;

    val title: String
        get() = when (this) {
            ALL -> "All"
            REAL -> VerdictType.REAL.shortLabel
            TAMPERED -> VerdictType.TAMPERED.shortLabel
            AI -> VerdictType.AI.shortLabel
        }

    fun matches(item: VerificationCase): Boolean = when (this) {
        ALL -> true
        REAL -> item.verdict == VerdictType.REAL
        TAMPERED -> item.verdict == VerdictType.TAMPERED
        AI -> item.verdict == VerdictType.AI
    }
}

/**
 * Plain-language copy for freshly analyzed images. It describes what the
 * detector concluded and what the user can check themselves; it never claims
 * specific visual evidence the model didn't report.
 */
data class VerdictCopy(
    val summary: String,
    val action: String,
    /** Things the user can look for to confirm or challenge the verdict. */
    val findings: List<String>,
) {
    companion object {
        fun forVerdict(verdict: VerdictType): VerdictCopy = when (verdict) {
            VerdictType.REAL -> VerdictCopy(
                summary = "The detector didn't find strong signs that this image was generated by AI. That isn't proof it's genuine: it can still be edited or shared with a misleading caption.",
                action = "Check who posted it first and whether the caption fits before sharing.",
                findings = listOf(
                    "Shadows and lighting agree across the whole scene",
                    "The same event appears in other people's photos",
                    "The caption's date and place match what's shown",
                ),
            )
            VerdictType.TAMPERED -> VerdictCopy(
                summary = "Part of this photo looks inconsistent with the rest, as if something was added, removed or retouched.",
                action = "Look for the original photo before sharing it.",
                findings = listOf(
                    "One area sharper or softer than its surroundings",
                    "Edges that look cut out or smudged",
                    "Text that stays flat where the surface bends",
                ),
            )
            VerdictType.AI -> VerdictCopy(
                summary = "The detector found patterns it associates with AI-generated images.",
                action = "Don't share it as a real photo without confirming where it came from.",
                findings = listOf(
                    "Hands, teeth and text: extra fingers or letters that don't spell anything",
                    "Pairs that don't match, like earrings or glasses",
                    "Hair or edges that melt into the background",
                ),
            )
        }
    }
}
